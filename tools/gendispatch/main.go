// Command gendispatch reads the patched OpenAPI spec and writes
// dispatch.gen.go: gen.BuildRequest, a table that maps an operationId to the
// request builder oapi-codegen generated for it.
//
// Usage: go run ./tools/gendispatch <spec.json> <out.go>
package main

import (
	"bytes"
	"errors"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"sort"
	"strings"

	"github.com/getkin/kin-openapi/openapi3"
)

func main() {
	if err := run(os.Args[1:]); err != nil {
		fmt.Fprintln(os.Stderr, "gendispatch:", err)
		os.Exit(1)
	}
}

func run(args []string) error {
	if len(args) != 2 {
		return errors.New("usage: gendispatch <spec.json> <out.go>")
	}
	data, err := os.ReadFile(args[0])
	if err != nil {
		return err
	}
	doc, err := openapi3.NewLoader().LoadFromData(data)
	if err != nil {
		return fmt.Errorf("load spec: %w", err)
	}
	ops, err := collect(doc)
	if err != nil {
		return err
	}
	src, err := render(ops)
	if err != nil {
		return err
	}
	return os.WriteFile(args[1], src, 0o644)
}

type operation struct {
	ID        string
	PathTypes []string // Go type per path parameter (always int64), template order
	HasQuery  bool
	HasBody   bool
}

var placeholder = regexp.MustCompile(`\{([^}]+)\}`)

func collect(doc *openapi3.T) ([]operation, error) {
	var ops []operation
	seen := map[string]bool{}
	for path, item := range doc.Paths.Map() {
		for method, op := range item.Operations() {
			if op.OperationID == "" {
				return nil, fmt.Errorf("%s %s has no operationId", method, path)
			}
			if seen[op.OperationID] {
				return nil, fmt.Errorf("duplicate operationId %s", op.OperationID)
			}
			seen[op.OperationID] = true

			o := operation{ID: op.OperationID, HasBody: op.RequestBody != nil}
			// Operation-level parameters win over path-level ones.
			params := map[string]*openapi3.Parameter{}
			for _, list := range []openapi3.Parameters{item.Parameters, op.Parameters} {
				for _, p := range list {
					if p.Value == nil {
						continue
					}
					switch p.Value.In {
					case "path":
						params[p.Value.Name] = p.Value
					case "query":
						o.HasQuery = true
					default:
						return nil, fmt.Errorf("%s: unsupported parameter location %q", o.ID, p.Value.In)
					}
				}
			}
			for _, m := range placeholder.FindAllStringSubmatch(path, -1) {
				p := params[m[1]]
				if p == nil {
					return nil, fmt.Errorf("%s: path parameter %q is not declared", o.ID, m[1])
				}
				typ, err := goType(p)
				if err != nil {
					return nil, fmt.Errorf("%s: %w", o.ID, err)
				}
				o.PathTypes = append(o.PathTypes, typ)
			}
			ops = append(ops, o)
		}
	}
	sort.Slice(ops, func(i, j int) bool { return ops[i].ID < ops[j].ID })
	return ops, nil
}

// goType returns the Go type of a path parameter. BuildRequest takes []int64,
// so only integer/int64 parameters are supported; anything else would need a
// narrowing conversion and is a generator error.
func goType(p *openapi3.Parameter) (string, error) {
	if p.Schema == nil || p.Schema.Value == nil || !p.Schema.Value.Type.Is("integer") || p.Schema.Value.Format != "int64" {
		return "", fmt.Errorf("path parameter %q must be integer/int64", p.Name)
	}
	return "int64", nil
}

func render(ops []operation) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(`// Code generated by tools/gendispatch from the patched OpenAPI spec. DO NOT EDIT.

package gen

import (
	"errors"
	"fmt"
	"io"
	"net/http"
	"net/url"
)

// Errors returned by BuildRequest. They signal programming errors (a wrong
// operation ID or argument list), never user input; callers wrap them.
var (
	ErrUnknownOperation = errors.New("unknown operation")
	ErrPathParams       = errors.New("wrong number of path parameters")
	ErrUnexpectedBody   = errors.New("operation takes no request body")
)

// BuildRequest builds the HTTP request of operation opID with the generated
// request builder. pathParams are the path parameters in template order, query
// is encoded into the URL when not empty. body (with contentType) is only
// allowed for operations that declare a request body. server must end with a
// slash ("https://host/api/v1/"): the generated builders resolve the operation
// path relative to it, which drops the last path segment otherwise.
func BuildRequest(opID, server string, pathParams []int64, query url.Values, contentType string, body io.Reader) (*http.Request, error) {
	req, err := build(opID, server, pathParams, contentType, body)
	if err != nil {
		return nil, err
	}
	if len(query) > 0 {
		req.URL.RawQuery = query.Encode()
	}
	return req, nil
}

func build(opID, server string, ids []int64, contentType string, body io.Reader) (*http.Request, error) {
	switch opID {
`)
	for _, o := range ops {
		n := len(o.PathTypes)
		fmt.Fprintf(&b, "\tcase %q:\n", o.ID)
		fmt.Fprintf(&b, "\t\tif len(ids) != %d {\n\t\t\treturn nil, pathParamsError(opID, %d, len(ids))\n\t\t}\n", n, n)
		args := []string{"server"}
		for i := range o.PathTypes {
			args = append(args, fmt.Sprintf("ids[%d]", i))
		}
		if o.HasQuery {
			args = append(args, "nil")
		}
		if o.HasBody {
			args = append(args, "contentType", "body")
			fmt.Fprintf(&b, "\t\treturn New%sRequestWithBody(%s)\n", o.ID, strings.Join(args, ", "))
		} else {
			fmt.Fprintf(&b, "\t\tif body != nil {\n\t\t\treturn nil, fmt.Errorf(\"%%w: %%s\", ErrUnexpectedBody, opID)\n\t\t}\n")
			fmt.Fprintf(&b, "\t\treturn New%sRequest(%s)\n", o.ID, strings.Join(args, ", "))
		}
	}
	b.WriteString(`	}
	return nil, fmt.Errorf("%w: %s", ErrUnknownOperation, opID)
}

func pathParamsError(opID string, want, got int) error {
	return fmt.Errorf("%w: %s takes %d, got %d", ErrPathParams, opID, want, got)
}
`)
	return format.Source(b.Bytes())
}
